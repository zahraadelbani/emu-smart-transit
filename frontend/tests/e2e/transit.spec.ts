test('staff assignment changes, moving fixes, outage and recovery',async({page,context})=>{
 await page.goto('/staff')
 await page.getByLabel('Username',{exact:true}).fill('e2e-dispatcher')
 await page.getByLabel('Password',{exact:true}).fill(process.env.E2E_PASSWORD!)
 await page.getByRole('button',{name:'Sign in',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Transportation control'})).toBeVisible()
 await page.getByRole('tab',{name:'buses',exact:true}).click()
 await page.getByRole('button',{name:'Add new',exact:true}).click()
 await page.getByLabel('Fleet number',{exact:true}).fill('E2E-STAFF-CREATED')
 await page.getByLabel('Display name',{exact:true}).fill('Staff-created vehicle')
 await page.getByRole('button',{name:'Save',exact:true}).click()
 await expect(page.getByRole('status')).toContainText('Saved successfully')
 await expect(page.locator('.record-list')).toContainText('Staff-created vehicle')
 await page.getByRole('tab',{name:'assignments',exact:true}).click()
 const card=page.locator('.assignment-card').filter({has:page.getByRole('heading',{name:'Campus bus 01',exact:true})})
 await card.getByLabel('Route for Campus bus 01').selectOption({label:'DEMO · 1 + 4 · from_emu'})
 await card.getByRole('button',{name:'Activate assignment'}).click()
 await expect(page.getByRole('status')).toContainText('Assignment updated')
 const student=await context.newPage()
 await student.goto('/')
 await expect(student.getByRole('button',{name:/Campus bus 01/})).toContainText('Military Guesthouse')
 const before=await student.request.get('/api/v1/buses/live/').then(r=>r.json())
 await expect.poll(async()=>{const after=await student.request.get('/api/v1/buses/live/').then(r=>r.json());return after.results[0].position.fix_time}).not.toBe(before.results[0].position.fix_time)
 await page.getByRole('tab',{name:'simulation',exact:true}).click()
 await page.getByRole('button',{name:'Pause',exact:true}).click()
 await expect.poll(async()=>{const data=await student.request.get('/api/v1/buses/live/').then(r=>r.json());return data.results.every((b:any)=>b.status==='offline')},{timeout:20000}).toBe(true)
 await expect(student.locator('.bus-list .state.offline')).toHaveCount(5,{timeout:15000})
 await page.getByRole('button',{name:'Start',exact:true}).click()
 await expect.poll(async()=>{const data=await student.request.get('/api/v1/buses/live/').then(r=>r.json());return data.results.every((b:any)=>b.status==='live')},{timeout:15000}).toBe(true)
 await student.close()
})

for(const width of [375,390,768,1024,1440])test(`responsive layout ${width}px`,async({page})=>{
 await page.setViewportSize({width,height:900})
 await page.goto('/')
 await expect(page.locator('.vehicle-marker')).toHaveCount(5)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
 await page.screenshot({path:`test-results/map-${width}.png`,fullPage:true})
 if(width<700){await page.getByRole('button',{name:'Toggle navigation'}).click();await page.getByRole('link',{name:'Timetable',exact:true}).click()}else await page.getByRole('link',{name:'Timetable',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Timetable',exact:true})).toBeVisible()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
})

test('API failure and denied geolocation remain usable',async({page})=>{
 await page.route('**/api/v1/buses/live/',route=>route.fulfill({status:503,body:'Service unavailable'}))
 await page.goto('/')
 await expect(page.getByRole('alert')).toContainText('Transportation data is unavailable',{timeout:15000})
 await page.getByRole('button',{name:'Find nearby stops'}).click()
 await expect(page.getByRole('status')).toContainText('Location permission',{timeout:15000})
})
